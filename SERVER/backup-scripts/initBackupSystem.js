const fs = require('fs');
const path = require('path');
// Initialize backup system directory and files
const initializeBackupSystem = () => {
  // Create backup directory if it doesn't exist
  const backupDir = path.join(__dirname, 'backups');
  if (!fs.existsSync(backupDir)) {
    fs.mkdirSync(backupDir, { recursive: true });
    } else {
    }
  // Create .gitignore for backup directory to prevent committing backup files
  const gitignorePath = path.join(backupDir, '.gitignore');
  if (!fs.existsSync(gitignorePath)) {
    fs.writeFileSync(gitignorePath, '# Ignore all backup files\n*.gz\n*.zip\n*.tar\n\n# Keep this directory\n!.gitignore\n');
    }
  // Create README for backup directory
  const readmePath = path.join(backupDir, 'README.md');
  if (!fs.existsSync(readmePath)) {
    const readmeContent = `# Database Backups Directory
This directory contains database backup files created by the FMIS Budget System.
## File Format
- All backup files are compressed using gzip (.gz extension)
- Files are named with timestamp: backup_YYYY-MM-DDTHH-mm-ss.gz
## Security
- Backup files contain sensitive data
- Do not commit these files to version control
- Ensure proper file permissions are set
## Maintenance
- Files are automatically cleaned up based on retention policy
- Default retention: 30 days
- Manual cleanup can be performed through the admin interface
## Directory Structure
\`\`\`
backups/
├── .gitignore          # Git ignore rules
├── README.md           # This file
└── *.gz               # Backup files (ignored by git)
\`\`\`
*Generated by FMIS Budget System*
`;
    fs.writeFileSync(readmePath, readmeContent);
    }
  // Set directory permissions (if on Unix-like system)
  try {
    if (process.platform !== 'win32') {
      fs.chmodSync(backupDir, '755');
      }
  } catch (error) {
    }
  };
// Run if called directly
if (require.main === module) {
  initializeBackupSystem();
}
module.exports = { initializeBackupSystem };