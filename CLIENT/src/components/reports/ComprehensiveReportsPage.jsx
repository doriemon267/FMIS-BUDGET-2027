import React, { useState, useEffect } from "react";
import {
  Box,
  Typography,
  Card,
  CardContent,
  Select,
  MenuItem,
  FormControl,
  InputLabel,
  Button,
  Grid,
  Chip,
  CircularProgress,
  Alert,
  Paper,
  IconButton,
  List,
  ListItem,
  ListItemText,
  Divider,
  useTheme,
  alpha,
  Stack,
  Avatar,
  Tooltip,
  Collapse,
  Dialog,
  DialogContent,
  AppBar,
  Toolbar,
} from "@mui/material";
import {
  AccountBalance,
  Group,
  Business,
  Construction,
  Category,
  Assessment,
  FileDownload,
  Summarize,
  ExpandMore,
  ExpandLess,
  Close,
} from "@mui/icons-material";
import PesoIcon from "../icons/PesoIcon";
import api from "../../config/api";
import ReportPageLayout from "./ReportPageLayout";
import GenericPdfPreviewDialog from "../GenericPdfPreviewDialog";
import { toast } from "react-toastify";
import { isBRDLevelUser, hasApproverRole, isHighLevelAccess } from "../../constants/roles";


// Custom hook for user restrictions
import { useUserRestrictions } from "../../hooks/useUserRestrictions";
import { AccessStatusIndicator } from "../common/AccessStatusIndicator";
import { useUser } from "../../context/UserContext";



const ComprehensiveReportsPage = () => {
  const theme = useTheme();
  const { getFilteredOptions } = useUserRestrictions();
  const { currentUser } = useUser();

  // State management (Moved up to avoid ReferenceError in hooks below)
  const [selectedRegion, setSelectedRegion] = useState("all");
  const [availableRegions, setAvailableRegions] = useState([]);
  const [availableFiscalYears, setAvailableFiscalYears] = useState([]);
  const [availableBudgetTypes, setAvailableBudgetTypes] = useState([]);
  const [reportData, setReportData] = useState(null);
  const [loading, setLoading] = useState(false);
  const [pdfLoading, setPdfLoading] = useState(false);
  const [error, setError] = useState(null);
  const [loadingInitialData, setLoadingInitialData] = useState(true);
  const [selectedFiscalYear, setSelectedFiscalYear] = useState("");
  const [selectedBudgetType, setSelectedBudgetType] = useState("");
  const [viewBy, setViewBy] = useState("region");
  const [availableOffices, setAvailableOffices] = useState([]);
  const [availableResponsibilityCenters, setAvailableResponsibilityCenters] = useState([]);
  const [selectedOffice, setSelectedOffice] = useState("all");
  const [selectedResponsibilityCenter, setSelectedResponsibilityCenter] = useState("all");
  const [autoGenerated, setAutoGenerated] = useState(false);
  const [expandedMooeCoKeys, setExpandedMooeCoKeys] = useState(() => new Set());
  const [pdfDialogOpen, setPdfDialogOpen] = useState(false);
  const [pdfPreviewUrl, setPdfPreviewUrl] = useState("");

  // --- ROLE-BASED SCOPING LOGIC ---
  const isHighLevel = React.useMemo(() => isHighLevelAccess(currentUser), [currentUser]);
  const isBRD = React.useMemo(() => isBRDLevelUser(currentUser), [currentUser]);
  const userScope = React.useMemo(() => String(currentUser?.hierarchicalAccess?.scope || currentUser?.hierarchicalAccess?.assignmentLevel || "").toUpperCase(), [currentUser]);
  
  // Restricted means either not high level (preparer) or an approver who is restricted to a unit (not BRD)
  const isRestricted = React.useMemo(() => !isHighLevel || (!isBRD && (userScope === 'DEPARTMENT' || userScope === 'DIVISION' || userScope === 'OFFICE' || userScope === 'RESPONSIBILITY_CENTER')), [isHighLevel, isBRD, userScope]);
  
  // Get user's assigned office/department or responsibility center/division
  const userDepartmentObj = currentUser?.hierarchicalAccess?.accessibleDepartments?.[0];
  const userDepartment = userDepartmentObj?.departmentName || userDepartmentObj?.name || userDepartmentObj;
  const userDivisionObj = currentUser?.hierarchicalAccess?.accessibleDivisions?.[0];
  const userDivision = userDivisionObj?.name || userDivisionObj;

  // Enforce restrictions based on role/scope
  useEffect(() => {
    if (isRestricted) {
      // Auto-set viewBy for non-BRD users based on their assignment
      let initialViewBy = "region";
      if (userScope === "DEPARTMENT" || userScope === "OFFICE" || userDepartment) {
        initialViewBy = "office";
      } else if (userScope === "DIVISION" || userScope === "RESPONSIBILITY_CENTER" || userDivision) {
        initialViewBy = "responsibilityCenter";
      }
      
      if (viewBy !== initialViewBy && !autoGenerated) {
        setViewBy(initialViewBy);
      }

      // Pre-select user's assignment
      if (userDepartment && selectedOffice === "all") {
        setSelectedOffice(String(userDepartment));
      }
      if (userDivision && selectedResponsibilityCenter === "all") {
        setSelectedResponsibilityCenter(String(userDivision));
      }
    }
  }, [isRestricted, userScope, userDepartment, userDivision, selectedOffice, selectedResponsibilityCenter, viewBy, autoGenerated]);

  useEffect(() => {
    return () => {
      if (pdfPreviewUrl) {
        window.URL.revokeObjectURL(pdfPreviewUrl);
      }
    };
  }, [pdfPreviewUrl]);

  const closePdfDialog = () => {
    setPdfDialogOpen(false);
    if (pdfPreviewUrl) {
      window.URL.revokeObjectURL(pdfPreviewUrl);
      setPdfPreviewUrl("");
    }
  };

  useEffect(() => {
    if (!reportData?.sections) return;
    const keys = new Set();
    reportData.sections.forEach((sec) => {
      if (sec.sectionCode === "B.1.2" || sec.sectionCode === "B.2") {
        Object.values(sec.categories || {}).forEach((cat) => {
          if (cat?.name) keys.add(`${sec.sectionCode}-${cat.name}`);
        });
      }
    });
    if (keys.size > 0) setExpandedMooeCoKeys(keys);
  }, [reportData]);

  const toggleMooeCoExpand = (key) => {
    setExpandedMooeCoKeys((prev) => {
      const next = new Set(prev);
      if (next.has(key)) next.delete(key);
      else next.add(key);
      return next;
    });
  };

  useEffect(() => {
    const fetchInitialData = async () => {
      try {
        const [regionsResponse, fiscalYearsResponse, budgetTypesResponse, activeSettingsResponse] = await Promise.all([
          api.get("/api/comprehensive-reports/available-regions-comprehensive"),
          api.get("/api/comprehensive-reports/available-fiscal-years"),
          api.get("/api/comprehensive-reports/available-budget-types"),
          api.get("/api/comprehensive-reports/active-settings"),
        ]);
        setAvailableRegions(regionsResponse.data.regions || []);
        setAvailableFiscalYears(fiscalYearsResponse.data.fiscalYears || []);
        setAvailableBudgetTypes(budgetTypesResponse.data.budgetTypes || []);
        if (activeSettingsResponse.data.settings) {
          const { fiscalYear, budgetType } = activeSettingsResponse.data.settings;
          setSelectedFiscalYear(fiscalYear || "");
          setSelectedBudgetType(budgetType || "");
        }
      } catch (err) {
        console.error("Error fetching initial data:", err);
        setError(err.response?.data?.message || "Failed to load initial data.");
      } finally {
        setLoadingInitialData(false);
      }
    };
    fetchInitialData();
  }, []);

  useEffect(() => {
    if (viewBy !== "office" && viewBy !== "responsibilityCenter") return;
    const params = new URLSearchParams();
    if (selectedRegion && selectedRegion !== "all") params.append("region", selectedRegion);
    if (selectedFiscalYear) params.append("fiscalYear", selectedFiscalYear);
    const q = params.toString() ? `?${params}` : "";
    const urls = {
      office: `/api/comprehensive-reports/available-offices-comprehensive${q}`,
      responsibilityCenter: `/api/comprehensive-reports/available-responsibility-centers-comprehensive${q}`,
    };
    const url = urls[viewBy];
    if (!url) return;
    api.get(url)
      .then((res) => {
        if (viewBy === "office") {
          const offices = res.data?.offices || [];
          // Ensure user's assigned office is in the list (for non-BRD users)
          if (isRestricted && userDepartment && !offices.includes(String(userDepartment))) {
            offices.unshift(String(userDepartment));
          }
          setAvailableOffices(offices);
        } else {
          const rcs = res.data?.responsibilityCenters || [];
          // Ensure user's assigned RC is in the list (for non-BRD users)
          if (isRestricted && userDivision && !rcs.includes(String(userDivision))) {
            rcs.unshift(String(userDivision));
          }
          setAvailableResponsibilityCenters(rcs);
        }
      })
      .catch(() => {
        if (viewBy === "office") {
          // Even on error, include user's assignment for non-BRD users
          setAvailableOffices(isRestricted && userDepartment ? [String(userDepartment)] : []);
        } else {
          setAvailableResponsibilityCenters(isRestricted && userDivision ? [String(userDivision)] : []);
        }
      });
  }, [viewBy, selectedRegion, selectedFiscalYear, isRestricted, userDepartment, userDivision]);

  // Auto-generate report for non-BRD users when their assignment is loaded
  useEffect(() => {
    if (!isRestricted || autoGenerated || loadingInitialData) return;
    if (!selectedFiscalYear || !selectedBudgetType) return;
    
    // Wait a bit for offices/RCs to load if needed
    const timer = setTimeout(async () => {
      // For non-BRD users: auto-generate if they have office or RC assignment
      if (viewBy === "office" && selectedOffice && selectedOffice !== "all") {
        setLoading(true);
        setError(null);
        try {
          const params = new URLSearchParams({ fiscalYear: selectedFiscalYear, budgetType: selectedBudgetType });
          if (viewBy) params.append("groupBy", viewBy);
          if (selectedRegion && selectedRegion !== "all") params.append("regions", selectedRegion);
          if (selectedOffice && selectedOffice !== "all") params.append("offices", selectedOffice);
          const response = await api.get(`/api/comprehensive-reports/comprehensive-data?${params}`);
          setReportData(response.data.data);
          setAutoGenerated(true);
        } catch (err) {
          console.error("Error auto-generating report:", err);
          setError(err.response?.data?.message || "Failed to generate report.");
        } finally {
          setLoading(false);
        }
      } else if (viewBy === "responsibilityCenter" && selectedResponsibilityCenter && selectedResponsibilityCenter !== "all") {
        setLoading(true);
        setError(null);
        try {
          const params = new URLSearchParams({ fiscalYear: selectedFiscalYear, budgetType: selectedBudgetType });
          if (viewBy) params.append("groupBy", viewBy);
          if (selectedRegion && selectedRegion !== "all") params.append("regions", selectedRegion);
          if (selectedResponsibilityCenter && selectedResponsibilityCenter !== "all") params.append("responsibilityCenters", selectedResponsibilityCenter);
          const response = await api.get(`/api/comprehensive-reports/comprehensive-data?${params}`);
          setReportData(response.data.data);
          setAutoGenerated(true);
        } catch (err) {
          console.error("Error auto-generating report:", err);
          setError(err.response?.data?.message || "Failed to generate report.");
        } finally {
          setLoading(false);
        }
      }
    }, 500);
    
    return () => clearTimeout(timer);
  }, [selectedFiscalYear, selectedBudgetType, viewBy, selectedOffice, selectedResponsibilityCenter, selectedRegion, isHighLevel, loadingInitialData, autoGenerated]);

  const fetchReportData = async () => {
    setLoading(true);
    setError(null);
    try {
      const params = new URLSearchParams({ fiscalYear: selectedFiscalYear, budgetType: selectedBudgetType });
      if (viewBy) params.append("groupBy", viewBy);
      if (selectedRegion && selectedRegion !== "all") params.append("regions", selectedRegion);
      if (viewBy === "office" && selectedOffice && selectedOffice !== "all") params.append("offices", selectedOffice);
      if (viewBy === "responsibilityCenter" && selectedResponsibilityCenter && selectedResponsibilityCenter !== "all") params.append("responsibilityCenters", selectedResponsibilityCenter);
      const response = await api.get(`/api/comprehensive-reports/comprehensive-data?${params}`);
      const data = response.data.data;
      
      // Debug: Check if A.2 was added and log data structure
      if (data.sections?.find(s => s.sectionCode === "A.2")) {
      }
      
      // Debug: Log sample of data structure to understand subsidy fields
      if (data.sections && data.sections.length > 0) {
        // Check first section
        const sampleSection = data.sections[0];
        if (sampleSection.categories) {
          const sampleCategory = Object.values(sampleSection.categories)[0];
        }
        
        // Specifically check Capital Outlay (B.2) structure if it exists
        const capitalOutlaySection = data.sections.find(s => s.sectionCode === "B.2");
        if (capitalOutlaySection && capitalOutlaySection.categories) {
          const capitalCategory = Object.values(capitalOutlaySection.categories)[0];
          // Check a sample item from Capital Outlay (guard: categories may be empty)
          if (capitalCategory?.items) {
            const itemsArray = Array.isArray(capitalCategory.items) ? capitalCategory.items : Object.values(capitalCategory.items);
            if (itemsArray.length > 0) {
            }
          }
        }
      }
      
      // Add A.2 - BUDGETARY SUPPORT using backend summary so it matches Grand Total (no double-count / wrong sum)
      if (data.sections && !data.sections.find(s => s.sectionCode === "A.2")) {
        const summarySubsidy = data.summary && (Number(data.summary.totalSubsidy) >= 0 || Number(data.summary.grandTotal) >= 0)
          ? (Number(data.summary.totalSubsidy) || Number(data.summary.grandTotal) || 0)
          : 0;

        if (summarySubsidy > 0) {
          const budgetarySupportSection = {
            sectionCode: "A.2",
            sectionName: "BUDGETARY SUPPORT",
            sectionDescription: "Government subsidies and budgetary support allocations from all regions",
            sectionTotal: summarySubsidy,
            consolidatedData: true,
            categories: {
              government_subsidies: {
                name: "Government Subsidies & Support",
                description: "Total government funding across all budget categories",
                totalSubsidy: summarySubsidy,
                total: summarySubsidy
              }
            }
          };
          const a1Index = data.sections.findIndex((s) => s.sectionCode === "A.1");
          if (a1Index >= 0) {
            data.sections.splice(a1Index + 1, 0, budgetarySupportSection);
          } else {
            data.sections.unshift(budgetarySupportSection);
          }
        }
      }
      
      setReportData(data);
    } catch (err) {
      console.error("Error fetching report data:", err);
      setError(err.response?.data?.message || "Failed to fetch report data.");
    } finally {
      setLoading(false);
    }
  };

  const formatCurrency = (amount) => {
    const rounded = Math.round(Number(amount || 0) * 100) / 100;
    return new Intl.NumberFormat("en-PH", { style: "currency", currency: "PHP", minimumFractionDigits: 2, maximumFractionDigits: 2 }).format(rounded);
  };

  const formatSignedDate = (value) => {
    if (!value) return "N/A";
    const date = new Date(value);
    if (Number.isNaN(date.getTime())) return "N/A";
    return date.toLocaleString("en-US");
  };

  const getSectionIcon = (sectionCode) => {
    switch (sectionCode) {
      case "A.1": return <AccountBalance />;
      case "A.2": return <PesoIcon />;
      case "B.1.1": return <Group />;
      case "B.1.2": return <Business />;
      case "B.2": return <Construction />;
      default: return <Category />;
    }
  };

  const getReportFilters = () => ({
    region: selectedRegion === 'all' ? 'All' : selectedRegion,
    fiscalYear: selectedFiscalYear,
    budgetType: selectedBudgetType,
  });

  const getApiErrorMessage = async (err, fallbackMessage) => {
    const directMessage = err?.response?.data?.message;
    if (typeof directMessage === "string" && directMessage.trim()) {
      return directMessage;
    }

    const responseData = err?.response?.data;
    if (responseData instanceof Blob) {
      try {
        const text = await responseData.text();
        if (text) {
          try {
            const parsed = JSON.parse(text);
            const parsedMessage = parsed?.message;
            if (typeof parsedMessage === "string" && parsedMessage.trim()) {
              return parsedMessage;
            }
          } catch (_parseErr) {
          }

          if (text.trim()) {
            return text.trim();
          }
        }
      } catch (_blobErr) {
      }
    }

    return fallbackMessage;
  };

  const handlePreviewPdf = async () => {
    setPdfLoading(true);
    setError(null);
    try {
      const params = new URLSearchParams({
        fiscalYear: selectedFiscalYear,
        budgetType: selectedBudgetType,
      });

      if (selectedRegion && selectedRegion !== "all") params.append("regions", selectedRegion);
      if (viewBy) params.append("groupBy", viewBy);
      if (viewBy === "office" && selectedOffice && selectedOffice !== "all") params.append("offices", selectedOffice);
      if (viewBy === "responsibilityCenter" && selectedResponsibilityCenter && selectedResponsibilityCenter !== "all") params.append("responsibilityCenters", selectedResponsibilityCenter);

      const response = await api.get(
        `/api/comprehensive-reports/comprehensive-pdf?${params.toString()}`,
        {
          responseType: "blob",
        }
      );

      const blob = new Blob([response.data], { type: "application/pdf" });
      const url = window.URL.createObjectURL(blob);
      if (pdfPreviewUrl) {
        window.URL.revokeObjectURL(pdfPreviewUrl);
      }
      setPdfPreviewUrl(url);
      setPdfDialogOpen(true);
    } catch (err) {
      console.error("Error generating PDF preview:", err);
      const message = await getApiErrorMessage(
        err,
        "Failed to generate PDF preview. Please try again."
      );
      setError(message);
      toast.error(message, { toastId: "comprehensive-pdf-preview-error" });
    } finally {
      setPdfLoading(false);
    }
  };

  return (
    <ReportPageLayout
      title="BUDGET SUMMARY REPORT"
      subtitle="Detailed budget analysis"
      showNiaBranding={true}
      breadcrumbLabel="Budget Summary Report"
      fiscalYear={selectedFiscalYear || new Date().getFullYear().toString()}
    >
      <AccessStatusIndicator />
      <Card elevation={4} sx={{ mb: 3, borderRadius: "16px" }}>
        <CardContent sx={{ p: 3 }}>
          {loadingInitialData && <Box sx={{ display: 'flex', justifyContent: 'center', mb: 2 }}><CircularProgress /></Box>}
          {isRestricted && (
            <Alert severity="info" sx={{ mb: 2 }}>
              Viewing report for your assigned {viewBy === "office" ? "Office/Department" : viewBy === "responsibilityCenter" ? "Responsibility Center" : "Region"}: <strong>{viewBy === "office" ? selectedOffice : viewBy === "responsibilityCenter" ? selectedResponsibilityCenter : selectedRegion}</strong>
            </Alert>
          )}
          <Grid container spacing={2} alignItems="center">
            <Grid item xs={12} sm={6} md={2}><FormControl fullWidth><InputLabel>View by</InputLabel><Select value={viewBy} onChange={(e) => { setViewBy(e.target.value); setSelectedOffice("all"); setSelectedResponsibilityCenter("all"); setAutoGenerated(false); }} label="View by" disabled={isRestricted}><MenuItem value="region">Region</MenuItem><MenuItem value="office">Office / Department</MenuItem><MenuItem value="responsibilityCenter">Responsibility Center</MenuItem></Select></FormControl></Grid>
            <Grid item xs={12} sm={6} md={2}><FormControl fullWidth><InputLabel>Region</InputLabel><Select value={selectedRegion} onChange={(e) => setSelectedRegion(e.target.value)} label="Region" disabled={isRestricted}><MenuItem value="all">All Regions</MenuItem>{availableRegions.map((r) => <MenuItem key={r} value={r}>{r}</MenuItem>)}</Select></FormControl></Grid>
            {viewBy === "office" && (<Grid item xs={12} sm={6} md={2}><FormControl fullWidth><InputLabel>Office / Department</InputLabel><Select value={selectedOffice} onChange={(e) => { setSelectedOffice(e.target.value); setAutoGenerated(false); }} label="Office / Department" disabled={isRestricted}><MenuItem value="all">All Offices</MenuItem>{availableOffices.map((o) => <MenuItem key={o} value={o}>{o}</MenuItem>)}</Select></FormControl></Grid>)}
            {viewBy === "responsibilityCenter" && (<Grid item xs={12} sm={6} md={2}><FormControl fullWidth><InputLabel>Responsibility Center</InputLabel><Select value={selectedResponsibilityCenter} onChange={(e) => { setSelectedResponsibilityCenter(e.target.value); setAutoGenerated(false); }} label="Responsibility Center" disabled={isRestricted}><MenuItem value="all">All RCs</MenuItem>{availableResponsibilityCenters.map((rc) => <MenuItem key={rc} value={rc}>{rc}</MenuItem>)}</Select></FormControl></Grid>)}
            <Grid item xs={12} sm={6} md={2}><FormControl fullWidth><InputLabel>Fiscal Year</InputLabel><Select value={selectedFiscalYear} onChange={(e) => setSelectedFiscalYear(e.target.value)} label="Fiscal Year">{getFilteredOptions(availableFiscalYears, 'fiscalYear').map((y) => <MenuItem key={y} value={y}>{y}</MenuItem>)}</Select></FormControl></Grid>
            <Grid item xs={12} sm={6} md={2}><FormControl fullWidth><InputLabel>Budget Type</InputLabel><Select value={selectedBudgetType} onChange={(e) => setSelectedBudgetType(e.target.value)} label="Budget Type">{getFilteredOptions(availableBudgetTypes, 'budgetType').map((t) => <MenuItem key={t} value={t}>{t}</MenuItem>)}</Select></FormControl></Grid>
            <Grid item xs={12} sm={6} md={2}>
              <Button
                variant="contained"
                fullWidth
                onClick={fetchReportData}
                disabled={loading}
                startIcon={
                  loading ? <CircularProgress size={20} /> : <Summarize />
                }
                sx={{ py: 1.5 }}
              >
                {loading ? "Generating..." : "Generate"}
              </Button>
            </Grid>
            {reportData && (
              <Grid item xs={12} sm={12} md={3}>
                <Button
                  variant="contained"
                  color="secondary"
                  fullWidth
                  onClick={handlePreviewPdf}
                  disabled={pdfLoading}
                  startIcon={
                    pdfLoading ? (
                      <CircularProgress size={20} />
                    ) : (
                      <FileDownload />
                    )
                  }
                  sx={{ py: 1.5 }}
                >
                  {pdfLoading ? "Creating PDF..." : "Preview PDF"}
                </Button>
              </Grid>
            )}
          </Grid>
        </CardContent>
      </Card>
      {error && <Alert severity="error" sx={{ mb: 3 }}>{error}</Alert>}

      {reportData?.summary?.approverNoProposals && (
        <Alert severity="info" sx={{ mb: 3 }}>
          No proposals have been passed to you yet. Report data will appear when proposals are forwarded to you in the workflow (e.g., Forwarded to Reviewer, Forwarded to Approver).
        </Alert>
      )}

      {reportData && (
        <Box>
          {/* ================================================================= */}
          {/* START OF UI FIX: Pinag-isang Table para sa MOOE at Capital Outlays */}
          {/* ================================================================= */}
          {reportData.sections.map((section) => {
            const isIncomeSection = section.sectionCode === "A.1";
            const isBudgetarySupport = section.sectionCode === "A.2";
            const isPersonnelServices = section.sectionCode === "B.1.1";
            const isDetailedExpense = section.sectionCode === "B.1.2" || section.sectionCode === "B.2";
            const isMooE = section.sectionCode === "B.1.2";
            const colIncome = "Projected Corporate Income";
            const colSubsidy = "Projected Subsidy";
            const colBudget = "Proposed Budget";

            return (
              <Paper key={section.sectionCode} elevation={2} sx={{ mb: 3, p: { xs: 2, md: 3 } }}>
                <Stack direction="row" justifyContent="space-between" alignItems="center" sx={{ borderBottom: 1, borderColor: 'divider', pb: 2, mb: 2 }}>
                  <Stack direction="row" alignItems="center" spacing={2}>
                    {getSectionIcon(section.sectionCode)}
                    <Box>
                      <Typography variant="h6" fontWeight="bold">
                        {section.sectionCode} - {section.sectionName}
                        {section.sectionCode === "A.2" && <Chip size="small" label="NEW" color="success" sx={{ ml: 1 }} />}
                      </Typography>
                      <Typography variant="body2" color="text.secondary">{section.sectionDescription}</Typography>
                    </Box>
                  </Stack>
                  <Chip label={formatCurrency(section.sectionTotal)} color="primary" />
                </Stack>
                
                {section.consolidatedData && (() => {
                  if (isIncomeSection) {
                    const cats = Object.values(section.categories || {});
                    return (
                      <Stack>
                        <Stack 
                          direction="row" 
                          sx={{ 
                            borderBottom: '2px solid #e2e8f0', 
                            pb: 1.5, 
                            pt: 1.5,
                            mb: 1, 
                            fontWeight: 700,
                            backgroundColor: '#f8fafc',
                            color: '#475569',
                            textTransform: 'uppercase',
                            fontSize: '0.75rem',
                            letterSpacing: '0.5px',
                            px: 2
                          }}
                        >
                          <Typography sx={{ width: '25%', fontSize: 'inherit', fontWeight: 'inherit' }}>Category</Typography>
                          <Typography sx={{ width: '25%', fontSize: 'inherit', fontWeight: 'inherit' }}>Description</Typography>
                          <Typography sx={{ width: '17%', textAlign: 'right', fontSize: 'inherit', fontWeight: 'inherit' }}>{colIncome}</Typography>
                          <Typography sx={{ width: '17%', textAlign: 'right', fontSize: 'inherit', fontWeight: 'inherit' }}>{colSubsidy}</Typography>
                          <Typography sx={{ width: '16%', textAlign: 'right', fontSize: 'inherit', fontWeight: 'inherit' }}>{colBudget}</Typography>
                        </Stack>
                        {cats.map((catData, idx) => (
                          <Stack key={idx} direction="row" sx={{ py: 1, borderBottom: '1px solid #eee' }}>
                            <Typography sx={{ width: '25%' }}>{catData.name}</Typography>
                            <Typography sx={{ width: '25%', color: 'text.secondary' }}>{catData.description || '-'}</Typography>
                            <Typography sx={{ width: '17%', textAlign: 'right' }}>{formatCurrency(catData.totalIncome)}</Typography>
                            <Typography sx={{ width: '17%', textAlign: 'right' }}>{formatCurrency(catData.totalSubsidy)}</Typography>
                            <Typography sx={{ width: '16%', textAlign: 'right', fontWeight: 'medium' }}>{formatCurrency(catData.total)}</Typography>
                          </Stack>
                        ))}
                        <Stack 
                          direction="row" 
                          sx={{ 
                            py: 2, 
                            mt: 1, 
                            borderTop: '2px solid #cbd5e1', 
                            fontWeight: 800, 
                            backgroundColor: '#f8fafc',
                            color: '#1e293b',
                            px: 2
                          }}
                        >
                          <Typography sx={{ width: '50%', fontWeight: 'inherit' }}>GRAND TOTAL</Typography>
                          <Typography sx={{ width: '17%', textAlign: 'right', fontWeight: 'inherit' }}>{formatCurrency(section.sectionTotalIncome)}</Typography>
                          <Typography sx={{ width: '17%', textAlign: 'right', fontWeight: 'inherit' }}>{formatCurrency(section.sectionTotalSubsidy)}</Typography>
                          <Typography sx={{ width: '16%', textAlign: 'right', fontWeight: 'inherit', color: '#375e38' }}>{formatCurrency(section.sectionTotal)}</Typography>
                        </Stack>
                      </Stack>
                    );
                  } 
                  
                  // Handle BUDGETARY SUPPORT section (A.2) – single total in table (Total row) to avoid repetition
                  else if (isBudgetarySupport) {
                    const categoriesList = Object.values(section.categories || {});
                    const totalAmount = section.sectionTotal ?? categoriesList.reduce((s, c) => s + (Number(c.totalSubsidy ?? c.total) || 0), 0);
                    const singleCategory = categoriesList.length <= 1;
                    return (
                      <Stack>
                        <Stack 
                          direction="row" 
                          sx={{ 
                            borderBottom: '2px solid #e2e8f0', 
                            pb: 1.5, 
                            pt: 1.5,
                            mb: 1, 
                            fontWeight: 700,
                            backgroundColor: '#f8fafc',
                            color: '#475569',
                            textTransform: 'uppercase',
                            fontSize: '0.75rem',
                            letterSpacing: '0.5px',
                            px: 2
                          }}
                        >
                          <Typography sx={{ width: '40%', fontSize: 'inherit', fontWeight: 'inherit' }}>Category</Typography>
                          <Typography sx={{ width: '35%', fontSize: 'inherit', fontWeight: 'inherit' }}>Description</Typography>
                          <Typography sx={{ width: '25%', textAlign: 'right', fontSize: 'inherit', fontWeight: 'inherit' }}>{colBudget}</Typography>
                        </Stack>
                        {categoriesList.map((cat, idx) => (
                          <Stack key={idx} direction="row" sx={{ py: 1, bgcolor: alpha(theme.palette.primary.main, 0.05) }}>
                            <Typography sx={{ width: '40%' }}>{cat.name || 'Budgetary Support'}</Typography>
                            <Typography sx={{ width: '35%', color: 'text.secondary' }}>{cat.description || 'Total government funding across all budget categories'}</Typography>
                            <Typography sx={{ width: '25%', textAlign: 'right' }}>
                              {singleCategory ? '—' : formatCurrency(cat.totalSubsidy ?? cat.total ?? 0)}
                            </Typography>
                          </Stack>
                        ))}
                        <Stack 
                          direction="row" 
                          sx={{ 
                            py: 2, 
                            mt: 1, 
                            borderTop: '2px solid #cbd5e1', 
                            fontWeight: 800, 
                            backgroundColor: '#f8fafc',
                            color: '#1e293b',
                            px: 2
                          }}
                        >
                          <Typography sx={{ width: '75%', fontWeight: 'inherit' }}>GRAND TOTAL</Typography>
                          <Typography sx={{ width: '25%', textAlign: 'right', fontWeight: 'inherit', color: '#375e38' }}>{formatCurrency(totalAmount)}</Typography>
                        </Stack>
                      </Stack>
                    );
                  }
                  
                  // B.1.1 Personnel Services - table with Projected Corporate Income, Projected Subsidy, Proposed Budget
                  else if (isPersonnelServices) {
                    const allRows = [];
                    Object.values(section.categories || {}).forEach(catData => {
                      allRows.push({ type: 'category', ...catData });
                      const itemsArray = Array.isArray(catData.items) ? catData.items : (catData.items ? Object.values(catData.items) : []);
                      itemsArray.forEach(item => allRows.push({ type: 'item', ...item }));
                    });
                    return (
                      <Stack>
                        <Stack 
                          direction="row" 
                          sx={{ 
                            borderBottom: '2px solid #e2e8f0', 
                            pb: 1.5, 
                            pt: 1.5,
                            mb: 1, 
                            fontWeight: 700,
                            backgroundColor: '#f8fafc',
                            color: '#475569',
                            textTransform: 'uppercase',
                            fontSize: '0.75rem',
                            letterSpacing: '0.5px',
                            px: 2
                          }}
                        >
                          <Typography sx={{ width: '25%', fontSize: 'inherit', fontWeight: 'inherit' }}>Category</Typography>
                          <Typography sx={{ width: '25%', fontSize: 'inherit', fontWeight: 'inherit' }}>Description</Typography>
                          <Typography sx={{ width: '17%', textAlign: 'right', fontSize: 'inherit', fontWeight: 'inherit' }}>{colIncome}</Typography>
                          <Typography sx={{ width: '17%', textAlign: 'right', fontSize: 'inherit', fontWeight: 'inherit' }}>{colSubsidy}</Typography>
                          <Typography sx={{ width: '16%', textAlign: 'right', fontSize: 'inherit', fontWeight: 'inherit' }}>{colBudget}</Typography>
                        </Stack>
                        {allRows.map((row, idx) => {
                          if (row.type === 'category') {
                            return (
                              <Stack key={idx} direction="row" sx={{ py: 1, fontWeight: 'bold', bgcolor: alpha(theme.palette.primary.main, 0.05) }}>
                                <Typography sx={{ width: '50%' }}>{row.name}</Typography>
                                <Typography sx={{ width: '17%', textAlign: 'right' }}>{formatCurrency(row.totalIncome)}</Typography>
                                <Typography sx={{ width: '17%', textAlign: 'right' }}>{formatCurrency(row.totalSubsidy)}</Typography>
                                <Typography sx={{ width: '16%', textAlign: 'right' }}>{formatCurrency(row.total)}</Typography>
                              </Stack>
                            );
                          }
                          return (
                            <Stack key={idx} direction="row" sx={{ py: 0.5, borderBottom: '1px solid #f0f0f0' }}>
                              <Typography sx={{ width: '25%', pl: 2, fontStyle: 'italic', color: 'text.secondary' }}></Typography>
                              <Typography variant="body2" sx={{ width: '25%' }}>{row.name}</Typography>
                              <Typography variant="body2" sx={{ width: '17%', textAlign: 'right' }}>{formatCurrency(row.income)}</Typography>
                              <Typography variant="body2" sx={{ width: '17%', textAlign: 'right' }}>{formatCurrency(row.subsidy)}</Typography>
                              <Typography variant="body2" sx={{ width: '16%', textAlign: 'right', fontWeight: 'medium' }}>{formatCurrency(row.amount)}</Typography>
                            </Stack>
                          );
                        })}
                        <Stack 
                          direction="row" 
                          sx={{ 
                            py: 2, 
                            mt: 1, 
                            borderTop: '2px solid #cbd5e1', 
                            fontWeight: 800, 
                            backgroundColor: '#f8fafc',
                            color: '#1e293b',
                            px: 2
                          }}
                        >
                          <Typography sx={{ width: '50%', fontWeight: 'inherit' }}>GRAND TOTAL</Typography>
                          <Typography sx={{ width: '17%', textAlign: 'right', fontWeight: 'inherit' }}>{formatCurrency(section.sectionTotalIncome)}</Typography>
                          <Typography sx={{ width: '17%', textAlign: 'right', fontWeight: 'inherit' }}>{formatCurrency(section.sectionTotalSubsidy)}</Typography>
                          <Typography sx={{ width: '16%', textAlign: 'right', fontWeight: 'inherit', color: '#375e38' }}>{formatCurrency(section.sectionTotal)}</Typography>
                        </Stack>
                      </Stack>
                    );
                  }
                  
                  // MOOE at Capital Outlays – Category + Subline Item (expandable)
                  else if (isDetailedExpense) {
                    const categories = Object.values(section.categories || {});
                    return (
                      <Stack>
                        <Stack 
                          direction="row" 
                          sx={{ 
                            borderBottom: '2px solid #e2e8f0', 
                            pb: 1.5, 
                            pt: 1.5,
                            mb: 1, 
                            fontWeight: 700,
                            backgroundColor: '#f8fafc',
                            color: '#475569',
                            textTransform: 'uppercase',
                            fontSize: '0.75rem',
                            letterSpacing: '0.5px',
                            px: 2
                          }}
                        >
                          <Typography sx={{ width: '25%', fontSize: 'inherit', fontWeight: 'inherit' }}>Category</Typography>
                          <Typography sx={{ width: '25%', fontSize: 'inherit', fontWeight: 'inherit' }}>Subline Item</Typography>
                          <Typography sx={{ width: '17%', textAlign: 'right', fontSize: 'inherit', fontWeight: 'inherit' }}>{colIncome}</Typography>
                          <Typography sx={{ width: '17%', textAlign: 'right', fontSize: 'inherit', fontWeight: 'inherit' }}>{colSubsidy}</Typography>
                          <Typography sx={{ width: '16%', textAlign: 'right', fontSize: 'inherit', fontWeight: 'inherit' }}>{colBudget}</Typography>
                        </Stack>
                        {categories.map((catData, catIdx) => {
                          const expandKey = `${section.sectionCode}-${catData.name}`;
                          const isExpanded = expandedMooeCoKeys.has(expandKey);
                          const itemsArray = Array.isArray(catData.items) ? catData.items : (catData.items ? Object.values(catData.items) : []);
                          const filteredItems = itemsArray.filter((item) => item && (item.amount || 0) > 0);
                          return (
                            <Box key={catIdx}>
                              <Stack
                                direction="row"
                                sx={{
                                  py: 1,
                                  fontWeight: 'bold',
                                  bgcolor: alpha(theme.palette.primary.main, 0.05),
                                  alignItems: 'center',
                                  cursor: 'pointer',
                                  '&:hover': { bgcolor: alpha(theme.palette.primary.main, 0.1) },
                                }}
                                onClick={() => toggleMooeCoExpand(expandKey)}
                              >
                                <IconButton size="small" sx={{ mr: 0, p: 0.5 }}>
                                  {isExpanded ? <ExpandLess /> : <ExpandMore />}
                                </IconButton>
                                <Typography sx={{ width: 'calc(25% - 40px)' }}>{catData.name}</Typography>
                                <Box sx={{ width: '25%' }} />
                                <Typography sx={{ width: '17%', textAlign: 'right' }}>{formatCurrency(catData.totalIncome)}</Typography>
                                <Typography sx={{ width: '17%', textAlign: 'right' }}>{formatCurrency(catData.totalSubsidy)}</Typography>
                                <Typography sx={{ width: '16%', textAlign: 'right' }}>{formatCurrency(catData.total)}</Typography>
                              </Stack>
                              <Collapse in={isExpanded} unmountOnExit>
                                {filteredItems.map((item, itemIdx) => {
                                  const sublineText = item.title ?? item.name ?? '—';
                                  const sublineParts = typeof sublineText === 'string'
                                    ? sublineText.split(/\s*[-•·∙]\s*/).map((s) => s.trim()).filter(Boolean)
                                    : [sublineText];
                                  return (
                                    <Stack key={itemIdx} direction="row" sx={{ py: 0.5, borderBottom: '1px solid #f0f0f0', pl: 5 }}>
                                      <Typography sx={{ width: '25%' }} />
                                      <Stack sx={{ width: '25%' }} spacing={0}>
                                        {sublineParts.length > 0
                                          ? sublineParts.map((part, i) => (
                                              <Typography key={i} variant="body2">{part}</Typography>
                                            ))
                                          : <Typography variant="body2">—</Typography>}
                                      </Stack>
                                      <Typography variant="body2" sx={{ width: '17%', textAlign: 'right' }}>{formatCurrency(item.income)}</Typography>
                                      <Typography variant="body2" sx={{ width: '17%', textAlign: 'right' }}>{formatCurrency(item.subsidy)}</Typography>
                                      <Typography variant="body2" sx={{ width: '16%', textAlign: 'right', fontWeight: 'medium' }}>{formatCurrency(item.amount)}</Typography>
                                    </Stack>
                                  );
                                })}
                              </Collapse>
                            </Box>
                          );
                        })}
                        <Stack 
                          direction="row" 
                          sx={{ 
                            py: 2, 
                            mt: 1, 
                            borderTop: '2px solid #cbd5e1', 
                            fontWeight: 800, 
                            backgroundColor: '#f8fafc',
                            color: '#1e293b',
                            px: 2
                          }}
                        >
                          <Typography sx={{ width: '50%', fontWeight: 'inherit' }}>GRAND TOTAL</Typography>
                          <Typography sx={{ width: '17%', textAlign: 'right', fontWeight: 'inherit' }}>{formatCurrency(Object.values(section.categories || {}).reduce((s, c) => s + (parseFloat(c.totalIncome) || 0), 0))}</Typography>
                          <Typography sx={{ width: '17%', textAlign: 'right', fontWeight: 'inherit' }}>{formatCurrency(Object.values(section.categories || {}).reduce((s, c) => s + (parseFloat(c.totalSubsidy) || 0), 0))}</Typography>
                          <Typography sx={{ width: '16%', textAlign: 'right', fontWeight: 'inherit', color: '#375e38' }}>{formatCurrency(section.sectionTotal)}</Typography>
                        </Stack>
                      </Stack>
                    );
                  } 
                  
                  else {
                    // Default na itsura para sa ibang sections
                    return Object.values(section.categories || {}).map((catData, idx) => (
                      <Box key={idx} sx={{ mb: 2 }}>
                        <Typography variant="subtitle1" fontWeight="bold">{catData.name}</Typography>
                        <List dense>
                          {(Array.isArray(catData.items) ? catData.items : Object.values(catData.items || {})).map((item, itemIdx) => (
                            <ListItem key={itemIdx} divider secondaryAction={<Typography variant="body2" fontWeight="bold">{formatCurrency(item.amount)}</Typography>}>
                              <ListItemText primary={item.name} />
                            </ListItem>
                          ))}
                        </List>
                      </Box>
                    ));
                  }
                })()}
              </Paper>
            );
          })}
          {/* Grand Total (Pangkalahatang Kabuuan) - Income, Subsidy, Proposed Budget */}
          {reportData?.summary && (
            <Paper elevation={3} sx={{ p: 3, mt: 3, background: `linear-gradient(135deg, ${theme.palette.primary.dark} 0%, ${theme.palette.secondary.dark} 100%)`, color: 'white', borderRadius: '16px' }}>
              <Typography variant="h5" fontWeight="bold" sx={{ mb: 2 }}>Grand Total</Typography>
              <Stack spacing={1.5}>
                <Stack direction="row" justifyContent="space-between" alignItems="center">
                  <Typography variant="body1">Projected Corporate Income</Typography>
                  <Typography variant="h6" fontWeight="bold">{formatCurrency(reportData.summary.totalIncome)}</Typography>
                </Stack>
                <Stack direction="row" justifyContent="space-between" alignItems="center">
                  <Typography variant="body1">Projected Subsidy</Typography>
                  <Typography variant="h6" fontWeight="bold">{formatCurrency(reportData.summary.totalSubsidy)}</Typography>
                </Stack>
                <Stack direction="row" justifyContent="space-between" alignItems="center" sx={{ borderTop: '2px solid rgba(255,255,255,0.3)', pt: 1.5, mt: 0.5 }}>
                  <Typography variant="body1" fontWeight="bold">Proposed Budget</Typography>
                  <Typography variant="h5" fontWeight="bold">{formatCurrency(reportData.summary.grandTotal)}</Typography>
                </Stack>
              </Stack>
            </Paper>
          )}

          {Array.isArray(reportData?.summary?.signatories) && reportData.summary.signatories.length > 0 && (
            <Paper elevation={2} sx={{ p: 3, mt: 3, borderRadius: '16px' }}>
              <Typography variant="h6" fontWeight="bold" sx={{ mb: 2 }}>
                Workflow Signatories
              </Typography>
              <Stack spacing={1.5}>
                {reportData.summary.signatories.map((signatory, index) => (
                  <Box
                    key={`${signatory.userId || signatory.fullName || 'signatory'}-${index}`}
                    sx={{
                      p: 1.5,
                      border: '1px solid',
                      borderColor: 'divider',
                      borderRadius: 1.5,
                      bgcolor: alpha(theme.palette.primary.main, 0.03),
                    }}
                  >
                    <Stack direction={{ xs: 'column', md: 'row' }} justifyContent="space-between" alignItems={{ xs: 'flex-start', md: 'center' }} spacing={1}>
                      <Box>
                        <Typography variant="subtitle2" fontWeight="bold">
                          {signatory.fullName || 'Unknown Signatory'}
                        </Typography>
                        <Typography variant="body2" color="text.secondary">
                          {signatory.position || 'Workflow Signatory'}
                        </Typography>
                      </Box>
                      <Stack direction="row" spacing={1} flexWrap="wrap" useFlexGap>
                        <Chip size="small" label={signatory.signatureType || 'Signature'} color="primary" variant="outlined" />
                        <Chip size="small" label={signatory.workflowRole || 'Role'} variant="outlined" />
                        <Chip size="small" label={`Signed: ${formatSignedDate(signatory.signedAt)}`} variant="outlined" />
                      </Stack>
                    </Stack>
                  </Box>
                ))}
              </Stack>
            </Paper>
          )}
          {/* ================================================================= */}
          {/* END OF UI FIX                                                   */}
          {/* ================================================================= */}
        </Box>
      )}

      <GenericPdfPreviewDialog
        open={pdfDialogOpen}
        onClose={closePdfDialog}
        pdfUrl={pdfPreviewUrl}
        title="Comprehensive Report PDF Preview"
        downloadFilename={`Comprehensive_Report_${selectedFiscalYear}_${selectedBudgetType}.pdf`}
      />

      {!reportData && !loading && (
        <Card elevation={0} sx={{ borderStyle: 'dashed', borderWidth: '2px', borderColor: 'divider' }}>
          <CardContent sx={{ textAlign: "center", py: 8 }}>
            <Avatar sx={{ width: 80, height: 80, bgcolor: 'action.hover', color: 'text.secondary', mx: "auto", mb: 3 }}><Assessment sx={{ fontSize: 40 }} /></Avatar>
            <Typography variant="h5" color="text.secondary" fontWeight="bold">Ready to Generate Report</Typography>
            <Typography variant="body1" color="text.secondary" sx={{ mt: 1 }}>Select your criteria and click "Generate" to view the report.</Typography>
          </CardContent>
        </Card>
      )}
    </ReportPageLayout>
  );
};

